"""
Streaming chat logic for llama.cpp provider.

Handles SSE response parsing, content/thinking buffering, tool call accumulation,
and WebSocket message sending with configurable flush thresholds.

TOKEN STATISTICS (Bulletproof Per-Request):
    The chat_stream() function now captures REAL token counts from llama.cpp's
    final SSE response chunk via the 'usage' field:
        - prompt_tokens:    Actual tokens sent as input/context
        - completion_tokens: Actual tokens generated by the model
        - eval_duration:     Time spent generating (nanoseconds)

    These are packaged into a TokenStats dataclass and returned alongside
    the response string. This eliminates the old module-level global approach
    which was broken for concurrent users.

    Return value is now a tuple: (response_str, TokenStats)

THINKING / REASONING MODE:
    When enable_thinking=True and the server supports reasoning (--reasoning on),
    llama.cpp emits 'reasoning_content' in delta chunks. This content is buffered
    and streamed to the UI as {type: "thinking"} WebSocket messages, displayed
    in a collapsible "Reasoning" block before the final answer.

HTTP CLIENT POOL:
    Uses shared httpx.AsyncClient from http_client module instead of creating
    new clients per request. Connection pooling reuses TCP connections and TLS
    sessions across all requests.
"""
